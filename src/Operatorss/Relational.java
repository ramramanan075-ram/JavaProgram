package Operatorss;

public class Relational {

    static void main(String[] args) {
        int a = 13;
        int b = 15;                  // relational operator
        System.out.println( a == b); // * == equal
        System.out.println( a != b); // * != not equal to
        System.out.println( a >= b); // * >= greater then  or equal to
        System.out.println( a <= b); // * <= less then  or equal to
        System.out.println( a < b);  // * <  less then
        System.out.println( a > b);  // * >  greater then



    }
}
