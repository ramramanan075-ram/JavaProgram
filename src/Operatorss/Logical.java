package Operatorss;

public class Logical {
    static void main(String[] args) {
        // Logical operator are it contain only boolean
        // And (&&) true + true = true , F+F=F,T+F=F,
        // OR (||) one true come is true , false + true = true
        // Not (!) it change like true is false, false to true
        boolean a = true;
        boolean b = false;
        System.out.println( a&&b);
        System.out.println(a||b);
        System.out.println(!a);
        System.out.println(!b);

    }
}

